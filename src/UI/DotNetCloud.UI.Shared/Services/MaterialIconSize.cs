namespace DotNetCloud.UI.Shared.Components.DataDisplay;

/// <summary>
/// Size variants for <see cref="MaterialIcon"/> component.
/// </summary>
public enum MaterialIconSize
{
    /// <summary>16px — inline text or small UI elements.</summary>
    Sm,

    /// <summary>24px — default icon size.</summary>
    Md,

    /// <summary>32px — larger UI elements, cards.</summary>
    Lg,

    /// <summary>48px — hero sections, empty states.</summary>
    Xl
}
